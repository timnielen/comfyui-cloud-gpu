"""Endpoint manifests (endpoints/<name>/manifest.json) and the Dockerfiles generated from them.

Imported by the plugin and by tools/gen_dockerfile.py, so it must not import ComfyUI modules.
"""
import json
import os
import re
import shlex
import subprocess

PLUGIN_DIR = os.path.dirname(os.path.abspath(__file__))
ENDPOINTS_DIR = os.path.join(PLUGIN_DIR, "endpoints")
COMFY_DIR = os.path.dirname(os.path.dirname(PLUGIN_DIR))
COMFYUI_URL = "https://github.com/Comfy-Org/ComfyUI"
ENDPOINT_NAME = re.compile(r"[a-z0-9][a-z0-9_-]{0,40}")
MODEL_PATH = re.compile(r"[^/\\\x00-\x1f][^\\\x00-\x1f]*")  # relative, no backslashes or control characters; ".." is checked separately

HEADER = """\
# Generated by tools/gen_dockerfile.py from manifest.json. Do not edit.
# Build context: the comfy_cloud_run repository root.
FROM python:3.12-slim-bookworm

ENV PYTHONUNBUFFERED=1 PIP_NO_CACHE_DIR=1 PIP_DISABLE_PIP_VERSION_CHECK=1 \\
    NVIDIA_VISIBLE_DEVICES=all NVIDIA_DRIVER_CAPABILITIES=compute,utility,video
RUN apt-get update && apt-get install -y --no-install-recommends git curl ffmpeg libgl1 libglib2.0-0 \\
 && rm -rf /var/lib/apt/lists/*
"""

# Dependencies come after the models so a torch, ComfyUI or requirements change never re-downloads them.
DEPENDENCIES = """\
WORKDIR /comfyui
RUN pip install torch torchvision torchaudio --extra-index-url https://download.pytorch.org/whl/cu130
{comfyui}
RUN pip install -r requirements.txt
COPY worker/requirements.txt /tmp/worker-requirements.txt
RUN pip install -r /tmp/worker-requirements.txt
"""

FOOTER = """\
# Plugin code last: editing it only rebuilds this layer.
COPY . /comfyui/custom_nodes/comfy_cloud_run
CMD ["python", "custom_nodes/comfy_cloud_run/worker/handler.py"]
"""


# ComfyUI options the worker sets itself: its handler talks to ComfyUI and collects files through them.
WORKER_OPTIONS = ("--listen", "--port", "--base-directory", "--input-directory", "--output-directory", "--temp-directory")


def git_checkout(url, commit, path):
    """Shell commands that put `url` at `commit` into `path`, which may already exist (/comfyui holds the models)."""
    url, path = shlex.quote(url), shlex.quote(path)
    if commit is None:
        return f"git clone -q --depth 1 {url} {path}"
    return f"git init -q {path} && git -C {path} fetch -q --depth 1 {url} {shlex.quote(commit)} && git -C {path} checkout -q FETCH_HEAD"


def pack_name(url):
    return url.rstrip("/").rsplit("/", 1)[-1].removesuffix(".git")


def model_layer(model):
    path = shlex.quote(f"{model['directory']}/{model['name']}")
    return f"RUN curl -fsSL --retry 5 --create-dirs -o {path} {shlex.quote(model['url'])}\n"


def node_layer(node):
    path = "custom_nodes/" + pack_name(node["url"])
    req = shlex.quote(path + "/requirements.txt")
    return f"RUN {git_checkout(node['url'], node.get('commit'), path)} \\\n && if [ -f {req} ]; then pip install -r {req}; fi\n"


def dockerfile(manifest):
    comfyui = manifest["comfyui"]
    out = [HEADER, "\n# Models, one layer each.\nWORKDIR /comfyui/models\n"]
    out += [model_layer(m) for m in manifest["models"] if not m.get("runtime")]  # runtime entries: the worker installs them per job
    out += ["\n", DEPENDENCIES.format(comfyui="RUN " + git_checkout(comfyui["url"], comfyui.get("commit"), "/comfyui")), "\n# Custom nodes, one layer each.\n"]
    out += [node_layer(n) for n in manifest["custom_nodes"] if not n.get("runtime")]
    if manifest["pip"]:
        out.append("RUN pip install " + " ".join(shlex.quote(p) for p in manifest["pip"]) + "\n")
    out += ["\n", FOOTER]
    return "".join(out)


def format_manifest(manifest):
    """JSON with one list entry per line, so manifest diffs stay readable."""
    def value(v):
        if isinstance(v, list) and any(isinstance(x, dict) for x in v):
            return "[\n" + ",\n".join("    " + json.dumps(x) for x in v) + "\n  ]"
        return json.dumps(v)
    return "{\n" + ",\n".join(f"  {json.dumps(k)}: {value(v)}" for k, v in manifest.items()) + "\n}\n"


def check_manifest(manifest):
    """Raise ValueError for a manifest the Dockerfile can't be generated from. Manifests from the GUI go through this."""
    def strings(item, keys, optional=()):
        if not isinstance(item, dict) or not all(isinstance(item.get(k), str) and item[k] for k in keys) \
                or not all(isinstance(item[k], str) for k in optional if k in item):
            raise ValueError(f"expected {', '.join(keys)} in {item!r}")

    if not isinstance(manifest.get("endpoint_id"), str):
        raise ValueError("endpoint_id must be a string")
    strings(manifest.get("comfyui"), ("url",), ("commit",))
    for node in manifest.get("custom_nodes", []):
        strings(node, ("url",), ("commit",))
    for model in manifest.get("models", []):
        strings(model, ("name", "directory", "url"))
    for entry in manifest.get("custom_nodes", []) + manifest.get("models", []):
        if not isinstance(entry.get("runtime", False), bool):
            raise ValueError(f"runtime must be true or false in {entry!r}")
    for model in manifest.get("models", []):
        for part in (model["directory"], model["name"]):
            if not MODEL_PATH.fullmatch(part) or ".." in part.split("/"):
                raise ValueError(f"invalid model path {part!r}")
    if not all(isinstance(p, str) for p in manifest.get("pip", [])):
        raise ValueError("pip must be a list of strings")
    if not isinstance(manifest.get("comfy_args", ""), str):
        raise ValueError("comfy_args must be a string")
    for arg in shlex.split(manifest.get("comfy_args", "")):  # ValueError on unbalanced quotes
        if arg.split("=")[0] in WORKER_OPTIONS:
            raise ValueError(f"{arg.split('=')[0]} is set by the worker and can't be changed")


def endpoint_dir(name):
    if not ENDPOINT_NAME.fullmatch(name):
        raise ValueError(f"invalid endpoint name {name!r}: use lowercase letters, digits, - and _")
    return os.path.join(ENDPOINTS_DIR, name)


def endpoint_names():
    if not os.path.isdir(ENDPOINTS_DIR):
        return []
    return sorted(n for n in os.listdir(ENDPOINTS_DIR) if os.path.isfile(os.path.join(ENDPOINTS_DIR, n, "manifest.json")))


def load_manifest(name):
    with open(os.path.join(endpoint_dir(name), "manifest.json"), encoding="utf-8") as f:
        return json.load(f)


def save_manifest(name, manifest):
    """Write the manifest and regenerate its Dockerfile."""
    check_manifest(manifest)
    manifest = {"endpoint_id": manifest["endpoint_id"], "comfyui": manifest["comfyui"], "custom_nodes": manifest.get("custom_nodes", []),
                "pip": manifest.get("pip", []), "models": manifest.get("models", []),
                "comfy_args": manifest.get("comfy_args", "")}
    path = endpoint_dir(name)
    os.makedirs(path, exist_ok=True)
    with open(os.path.join(path, "manifest.json"), "w", encoding="utf-8") as f:
        f.write(format_manifest(manifest))
    with open(os.path.join(path, "Dockerfile"), "w", encoding="utf-8") as f:
        f.write(dockerfile(manifest))


def local_comfyui_commit(comfy_dir=COMFY_DIR):
    """The commit of the local ComfyUI checkout, or its release tag for an install that isn't a git checkout."""
    try:
        return subprocess.run(["git", "-C", comfy_dir, "rev-parse", "HEAD"], check=True, capture_output=True, text=True).stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        with open(os.path.join(comfy_dir, "comfyui_version.py"), encoding="utf-8") as f:
            return "v" + re.search(r'__version__ = "([^"]+)"', f.read()).group(1)


def new_manifest(comfy_dir=COMFY_DIR):
    return {"endpoint_id": "", "comfyui": {"url": COMFYUI_URL, "commit": local_comfyui_commit(comfy_dir)}, "custom_nodes": [], "pip": [], "models": []}
