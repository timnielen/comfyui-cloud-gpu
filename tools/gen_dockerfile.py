"""Write endpoints/<name>/Dockerfile from endpoints/<name>/manifest.json.

Usage: python tools/gen_dockerfile.py h3 [--pin-local]
--pin-local first sets the manifest's ComfyUI commit to the ComfyUI checkout this plugin is installed in,
so the cloud runs the same ComfyUI version as the local GUI. The commit must exist at the manifest's ComfyUI url.
The image is built with this plugin's repository root as build context.
"""
import json
import os
import shlex
import subprocess
import sys

PLUGIN_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COMFY_DIR = os.path.dirname(os.path.dirname(PLUGIN_DIR))

HEADER = """\
# Generated by tools/gen_dockerfile.py from manifest.json. Do not edit.
# Build context: the comfy_cloud_run repository root.
FROM python:3.12-slim-bookworm

ENV PYTHONUNBUFFERED=1 PIP_NO_CACHE_DIR=1 PIP_DISABLE_PIP_VERSION_CHECK=1 \\
    NVIDIA_VISIBLE_DEVICES=all NVIDIA_DRIVER_CAPABILITIES=compute,utility,video
RUN apt-get update && apt-get install -y --no-install-recommends git curl ffmpeg libgl1 libglib2.0-0 \\
 && rm -rf /var/lib/apt/lists/*
"""

# Dependencies come after the models so a torch, ComfyUI or requirements change never re-downloads them.
DEPENDENCIES = """\
WORKDIR /comfyui
RUN pip install torch torchvision torchaudio --extra-index-url https://download.pytorch.org/whl/cu130
{comfyui}
RUN pip install -r requirements.txt
COPY worker/requirements.txt /tmp/worker-requirements.txt
RUN pip install -r /tmp/worker-requirements.txt
"""

FOOTER = """\
# Plugin code last: editing it only rebuilds this layer.
COPY . /comfyui/custom_nodes/comfy_cloud_run
CMD ["python", "custom_nodes/comfy_cloud_run/worker/handler.py"]
"""


def git_checkout(url, commit, path):
    """Shell commands that put `url` at `commit` into `path`, which may already exist (/comfyui holds the models)."""
    url, path = shlex.quote(url), shlex.quote(path)
    if commit is None:
        return f"git clone -q --depth 1 {url} {path}"
    return f"git init -q {path} && git -C {path} fetch -q --depth 1 {url} {shlex.quote(commit)} && git -C {path} checkout -q FETCH_HEAD"


def model_layer(model):
    path = shlex.quote(f"{model['directory']}/{model['name']}")
    return f"RUN curl -fsSL --retry 5 --create-dirs -o {path} {shlex.quote(model['url'])}\n"


def node_layer(node):
    url = node["url"]
    path = "custom_nodes/" + url.rstrip("/").rsplit("/", 1)[-1].removesuffix(".git")
    req = shlex.quote(path + "/requirements.txt")
    return f"RUN {git_checkout(url, node.get('commit'), path)} \\\n && if [ -f {req} ]; then pip install -r {req}; fi\n"


def dockerfile(manifest):
    comfyui = manifest["comfyui"]
    out = [HEADER, "\n# Models, one layer each.\nWORKDIR /comfyui/models\n"]
    out += [model_layer(m) for m in manifest["models"]]
    out += ["\n", DEPENDENCIES.format(comfyui="RUN " + git_checkout(comfyui["url"], comfyui.get("commit"), "/comfyui")), "\n# Custom nodes, one layer each.\n"]
    out += [node_layer(n) for n in manifest["custom_nodes"]]
    if manifest["pip"]:
        out.append("RUN pip install " + " ".join(shlex.quote(p) for p in manifest["pip"]) + "\n")
    out += ["\n", FOOTER]
    return "".join(out)


def format_manifest(manifest):
    """JSON with one list entry per line, so manifest diffs stay readable."""
    def value(v):
        if isinstance(v, list) and any(isinstance(x, dict) for x in v):
            return "[\n" + ",\n".join("    " + json.dumps(x) for x in v) + "\n  ]"
        return json.dumps(v)
    return "{\n" + ",\n".join(f"  {json.dumps(k)}: {value(v)}" for k, v in manifest.items()) + "\n}\n"


def main():
    endpoint_dir = os.path.join(PLUGIN_DIR, "endpoints", sys.argv[1])
    manifest_path = os.path.join(endpoint_dir, "manifest.json")
    with open(manifest_path, encoding="utf-8") as f:
        manifest = json.load(f)
    if "--pin-local" in sys.argv[2:]:
        commit = subprocess.run(["git", "-C", COMFY_DIR, "rev-parse", "HEAD"], check=True, capture_output=True, text=True).stdout.strip()
        manifest["comfyui"]["commit"] = commit
        with open(manifest_path, "w", encoding="utf-8") as f:
            f.write(format_manifest(manifest))
        print(f"pinned ComfyUI to {commit}")
    path = os.path.join(endpoint_dir, "Dockerfile")
    with open(path, "w", encoding="utf-8") as f:
        f.write(dockerfile(manifest))
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
